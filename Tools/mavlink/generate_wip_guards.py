#!/usr/bin/env python3
"""
Generate mavlink_wip.h: the PX4_MAVLINK_WIP(<NAME>) guards for the MAVLink
definitions marked <wip> in a board's dialect and everything it includes.

Usage:
    generate_wip_guards.py --dialect development --output build/.../mavlink_wip.h

The header is always rewritten, so that its time stamp tells the build
system it is up to date with the XML.
"""

import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.realpath(__file__)))
import mavlink_flags  # noqa: E402

HEADER = '''\
/****************************************************************************
 *
 * Generated by Tools/mavlink/generate_wip_guards.py from {dialect}.xml.
 * Do not edit.
 *
 ****************************************************************************/

/**
 * @file mavlink_wip.h
 *
 * Guards for MAVLink definitions marked <wip> (work in progress), which
 * must not reach a release.
 *
 * Wrap every use of a WIP message, enum or enum entry, including a
 * VEHICLE_CMD_* or NAV_CMD_* constant whose number is a WIP MAV_CMD and a
 * stream name in a stream table, in
 *
 *     #if PX4_MAVLINK_WIP(<NAME>)
 *     ...
 *     #endif
 *
 * where <NAME> is the MAVLink name: a message (ESC_EEPROM), an enum
 * (ESC_FIRMWARE) or an enum entry (MAV_CMD_ACTUATOR_GROUP_TEST).
 *
 * PX4_MAVLINK_WIP(<NAME>) is 1 in dev builds (main, daily and untagged
 * builds) if <NAME> is WIP in this board's dialect. It is 0 in beta and
 * release builds, and when the dialect does not include <NAME>.
 *
 * In beta and release builds the WIP definitions are marked deprecated, so
 * any use outside a guard fails to compile. Run "make mavlink_wip_check" to
 * check before opening a pull request.
 *
 * Existing uses that ship unguarded for now are listed in
 * src/modules/mavlink/mavlink_wip_legacy.yaml, which may only shrink. Such
 * a use is wrapped in PX4_MAVLINK_WIP_LEGACY_BEGIN(<NAME>) and
 * PX4_MAVLINK_WIP_LEGACY_END.
 *
 * Once <NAME> is released (no longer WIP), remove its guard.
 * Tools/mavlink/check_wip.py reports guards for released definitions.
 */

#pragma once

#if !defined(PX4_MAVLINK_WIP_ENABLED) || !defined(PX4_MAVLINK_WIP_LEGACY_ENABLED)
#error "px4_mavlink_diagnostics.h missing: it is force-included by cmake/px4_add_common_flags.cmake"
#endif

#define PX4_MAVLINK_WIP(name) (PX4_MAVLINK_WIP_ENABLED && PX4_MAVLINK_WIP_ITEM_##name)

#if !PX4_MAVLINK_WIP_ENABLED && PX4_MAVLINK_WIP_LEGACY_ENABLED
#define PX4_MAVLINK_WIP_STRINGIFY(...) #__VA_ARGS__
#define PX4_MAVLINK_WIP_PRAGMA(x) PX4_MAVLINK_WIP_PRAGMA_(x)
#define PX4_MAVLINK_WIP_PRAGMA_(x) _Pragma(#x)
#define PX4_MAVLINK_WIP_LEGACY_BEGIN(name) \\
    PX4_MAVLINK_WIP_PRAGMA(message(PX4_MAVLINK_WIP_STRINGIFY( \\
        Legacy MAVLink WIP item name ships unguarded in this build (see mavlink_wip_legacy.yaml)))) \\
    _Pragma("GCC diagnostic push") \\
    _Pragma("GCC diagnostic ignored \\"-Wdeprecated-declarations\\"")
#define PX4_MAVLINK_WIP_LEGACY_END _Pragma("GCC diagnostic pop")
#else
#define PX4_MAVLINK_WIP_LEGACY_BEGIN(name)
#define PX4_MAVLINK_WIP_LEGACY_END
#endif

// WIP definitions in {dialect}.xml and the files it includes ({count})
'''


def generate(dialect, mavlink_dir):
    definitions = mavlink_flags.load(dialect, mavlink_dir)
    items = sorted(definitions.wip_items(), key=lambda item: item.name)
    lines = [HEADER.format(dialect=dialect, count=len(items))]

    for item in items:
        lines.append(f'#define PX4_MAVLINK_WIP_ITEM_{item.name} 1 // {item.kind}, {item.xml_file}\n')

    return ''.join(lines)


def write(path, content):
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)

    with open(path, 'w', encoding='utf-8') as output:
        output.write(content)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--dialect', default=mavlink_flags.DEFAULT_DIALECT,
                        help='MAVLink dialect, e.g. common or development')
    parser.add_argument('--mavlink-dir', default=mavlink_flags.DEFAULT_MAVLINK_DIR,
                        help='mavlink/mavlink checkout (default: the PX4 submodule)')
    parser.add_argument('--output', required=True, help='header to write')
    args = parser.parse_args()

    write(args.output, generate(args.dialect, args.mavlink_dir))


if __name__ == '__main__':
    main()
