/**
 * @file SkidToTurnAllocator.hpp
 *
 * Splits a lateral acceleration setpoint into a part generated by bank and a part generated by sideslip.
 * Bank always takes the remainder, so the sum of both parts equals the lateral acceleration setpoint.
 */

#pragma once

#include <lib/mathlib/mathlib.h>
#include <px4_platform_common/defines.h>
#include <slew_rate/SlewRate.hpp>

class SkidToTurnAllocator
{
public:
	struct Output {
		float bank; ///< [m/s^2] lateral acceleration to be generated by bank
		float skid; ///< [m/s^2] lateral acceleration to be generated by sideslip
	};

	/**
	 * @param skid_slew_rate [m/s^3] maximum rate of change of the sideslip part
	 */
	void setSlewRate(const float skid_slew_rate) { _skid_slew_rate.setSlewRate(skid_slew_rate); }

	/**
	 * @param lateral_acceleration [m/s^2] total lateral acceleration setpoint
	 * @param skid_ratio [-] fraction of the lateral acceleration to generate by sideslip, constrained to [0, 1]
	 * @param skid_acceleration_max [m/s^2] maximum lateral acceleration the sideslip may generate
	 * @param dt [s] time since last update
	 */
	Output update(const float lateral_acceleration, const float skid_ratio, const float skid_acceleration_max,
		      const float dt)
	{
		const float lateral_acceleration_finite = PX4_ISFINITE(lateral_acceleration) ? lateral_acceleration : 0.f;
		const float ratio = PX4_ISFINITE(skid_ratio) ? math::constrain(skid_ratio, 0.f, 1.f) : 0.f;
		const float skid_max = PX4_ISFINITE(skid_acceleration_max) ? math::max(skid_acceleration_max, 0.f) : 0.f;

		const float skid_target = math::constrain(ratio * lateral_acceleration_finite, -skid_max, skid_max);
		const float skid = _skid_slew_rate.update(skid_target, dt);

		return Output{lateral_acceleration_finite - skid, skid};
	}

	void reset() { _skid_slew_rate.setForcedValue(0.f); }

	float getSkid() const { return _skid_slew_rate.getState(); }

private:
	SlewRate<float> _skid_slew_rate{0.f};
};
